
num1 = int(input("첫번재  정수째 정수 입력 :"))
num2 = int(input("두번째  정수째 정수 입력 :"))
result = num1 + num2
print(num1, "+", num2, "=", result)

result = num1 - num2
print(num1, "-", num2, "=", result)

result = num1 * num2
print(num1, "*", num2, "=", result)

result = num1 / num2
print(num1, "/", num2, "=", result)

result = num1 // num2
print(num1, "//", num2, "=", result)

result = num1 % num2
print(num1, "%", num2, "=", result)


